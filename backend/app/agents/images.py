"""
Image generation for the blog pipeline.

Everything about turning an ImageSpec into a real picture (and handling it
when that fails) lives here, isolated from the rest of the agent/node logic
in agents.py:
  - calls Gemini's image model
  - retries once on transient-looking failures (rate limits, 5xx, timeouts)
  - summarizes raw provider errors into one clean log line (never leaked
    into the blog itself)
  - sanitizes any LLM-proposed filename before it's ever used as a path
  - the `generate_and_place_images` graph node that ties it all together

Keeping this in its own file means swapping providers, tuning retry
behavior, or debugging an API error only ever touches this one module.
"""
from __future__ import annotations

import logging
import os
import re
import time
from pathlib import Path
from typing import Any, Callable, Optional, Union

from google import genai
from google.genai import types

from langchain_core.messages import SystemMessage, HumanMessage
from langchain_core.runnables import RunnableConfig

from .agents_schemas import ImagePlanOutput, coerce_plan
from .states import State
from .prompts import DECIDE_IMAGES_SYSTEM
from .llms import get_llm
from workflow import mark_workflow_step


logger = logging.getLogger(__name__)


# ============================================================
# Resilient structured-output calls (self-contained copy of the same
# helper in agents.py - duplicated rather than imported so this module
# has zero dependency on agents.py, keeping the import graph one-directional:
# graph.py -> {agents.py, images.py}, agents.py -> images.py, and nothing
# ever imports back out of images.py. Keep both copies in sync if you
# change the retry/backoff behavior.)
# ============================================================
def _invoke_structured(
    structured_llm,
    messages: list,
    fallback: Union[Any, Callable[[], Any]],
    node_name: str,
    retries: int = 2,
):
    last_err: Optional[Exception] = None
    msgs = list(messages)
    for attempt in range(retries + 1):
        try:
            return structured_llm.invoke(msgs)
        except Exception as e:
            last_err = e
            if attempt < retries:
                msgs = msgs + [
                    HumanMessage(
                        content=(
                            "Your previous response could not be parsed into the "
                            "required structured schema. Respond again, strictly "
                            "matching the schema, with no extra commentary."
                        )
                    )
                ]
    logger.error("[%s] structured output failed after %d attempt(s): %s", node_name, retries + 1, last_err)
    return fallback() if callable(fallback) else fallback


# ============================================================
# Filenames: never trust an LLM-proposed filename as a real path
# ============================================================
_ALLOWED_IMAGE_EXTS = {".png", ".jpg", ".jpeg", ".webp", ".gif"}


def _safe_image_filename(name: Any, fallback_stem: str = "image") -> str:
    """
    The image filename comes from LLM structured output. Never trust it as
    a path: take only the basename (defeats '../../etc/...' traversal),
    slug it, and force an allowed image extension.
    """
    base = Path(str(name or "")).name  # strips any directory components
    stem = Path(base).stem
    ext = Path(base).suffix.lower()

    stem = re.sub(r"[^a-zA-Z0-9_-]+", "_", stem).strip("_") or fallback_stem
    if ext not in _ALLOWED_IMAGE_EXTS:
        ext = ".png"
    return f"{stem}{ext}"


def _safe_slug(title: str) -> str:
    s = title.strip().lower()
    s = re.sub(r"[^a-z0-9 _-]+", "", s)
    s = re.sub(r"\s+", "_", s).strip("_")
    return s or "blog"


# ============================================================
# Gemini image generation
# ============================================================
def _gemini_generate_image_bytes(prompt: str) -> bytes:
    """
    Returns raw image bytes generated by Gemini.
    Requires: pip install google-genai
    Env var: GOOGLE_API_KEY
    """
    api_key = os.environ.get("GOOGLE_API_KEY")
    if not api_key:
        raise RuntimeError("GOOGLE_API_KEY is not set.")

    client = genai.Client(api_key=api_key)

    resp = client.models.generate_content(
        model="gemini-2.5-flash-image",
        contents=prompt,
        config=types.GenerateContentConfig(
            response_modalities=["IMAGE"],
            safety_settings=[
                types.SafetySetting(
                    category="HARM_CATEGORY_DANGEROUS_CONTENT",
                    threshold="BLOCK_ONLY_HIGH",
                )
            ],
        ),
    )

    parts = getattr(resp, "parts", None)
    if not parts and getattr(resp, "candidates", None):
        try:
            parts = resp.candidates[0].content.parts
        except Exception:
            parts = None

    if not parts:
        raise RuntimeError("No image content returned (safety/quota/SDK change).")

    for part in parts:
        inline = getattr(part, "inline_data", None)
        if inline and getattr(inline, "data", None):
            return inline.data

    raise RuntimeError("No inline image bytes found in response.")


def _generate_image_bytes(prompt: str, width: int = 1024, height: int = 768) -> bytes:
    # width/height are accepted for a stable call signature (used by the
    # retry wrapper below) but Gemini's image model doesn't take explicit
    # dimensions, so they're unused here.
    return _gemini_generate_image_bytes(prompt)


# ============================================================
# Error handling: summarize + bounded retry
# ============================================================
_TRANSIENT_IMAGE_ERROR_MARKERS = (
    "resource_exhausted", "429", "502", "503", "504",
    "unavailable", "timeout", "timed out", "rate limit", "connection",
)


def _is_transient_image_error(e: Exception) -> bool:
    return any(marker in str(e).lower() for marker in _TRANSIENT_IMAGE_ERROR_MARKERS)


def _summarize_image_error(e: Exception) -> str:
    """
    Turns a raw provider exception (which can be a huge multi-line JSON blob,
    as with Gemini 429s) into one short, human-readable sentence. The full
    original error is logged separately for debugging - it never goes into
    the blog document itself.
    """
    msg = str(e).lower()
    if "resource_exhausted" in msg or "429" in msg or "quota" in msg or "rate limit" in msg:
        return "rate-limited or over quota on the image provider"
    if "google_api_key is not set" in msg:
        return "image generation isn't configured (missing GOOGLE_API_KEY)"
    if "safety" in msg or "no image content returned" in msg:
        return "the image model didn't return an image (likely blocked by a safety filter)"
    if "no inline image bytes" in msg:
        return "the image model's response didn't contain image data"
    if "timeout" in msg or "timed out" in msg:
        return "the image provider timed out"
    if "did not return an image" in msg:
        return "the image provider had a temporary issue and returned no image"
    if "connection" in msg:
        return "couldn't connect to the image provider"
    return "image generation failed unexpectedly"


def _generate_image_with_retry(
    prompt: str, width: int = 1024, height: int = 768, max_retries: int = 1, retry_delay_seconds: float = 4.0
) -> bytes:
    """
    Wraps _generate_image_bytes with one bounded retry for transient-looking
    failures (rate limits, 502/503/504, timeouts), then raises a single
    RuntimeError with a short, clean summary - never the raw provider
    exception - so callers can safely surface str(e) to the end user.
    """
    last_err: Optional[Exception] = None
    for attempt in range(max_retries + 1):
        try:
            return _generate_image_bytes(prompt, width=width, height=height)
        except Exception as e:
            last_err = e
            logger.warning("Image generation attempt %d/%d failed: %s", attempt + 1, max_retries + 1, e)
            if attempt < max_retries and _is_transient_image_error(e):
                time.sleep(retry_delay_seconds)
            else:
                break
    raise RuntimeError(_summarize_image_error(last_err)) from last_err


_SIZE_RE = re.compile(r"^\s*(\d+)\s*x\s*(\d+)\s*$", re.IGNORECASE)


def _parse_image_size(size_str: Optional[str], default: tuple = (1024, 768)) -> tuple:
    if size_str:
        m = _SIZE_RE.match(size_str)
        if m:
            return int(m.group(1)), int(m.group(2))
    return default


# ============================================================
# Graph node: decide whether/where images belong, and inject placeholders
# ============================================================
def decide_images(state: State) -> dict:
    mark_workflow_step(state.get("run_id"), "image-plan")
    llm = get_llm()
    planner = llm.with_structured_output(ImagePlanOutput)
    merged_md = state["merged_md"]
    plan = state["plan"]
    assert plan is not None
    plan = coerce_plan(plan)

    image_plan = _invoke_structured(
        planner,
        [
            SystemMessage(content=DECIDE_IMAGES_SYSTEM),
            HumanMessage(
                content=(
                    f"Blog kind: {plan.blog_kind}\n"
                    f"Topic: {state['topic']}\n\n"
                    f"Analyze the following markdown and propose image specs with their target section titles:\n\n"
                    f"{merged_md}"
                )
            ),
        ],
        fallback=lambda: ImagePlanOutput(images=[]),
        node_name="decide_images",
    )

    # Python-side deterministic placeholder injection to avoid LLM JSON serialization errors
    md_with_placeholders = merged_md
    image_specs_dict = []

    for idx, img in enumerate(image_plan.images, start=1):
        placeholder = f"[[IMAGE_{idx}]]"
        header_pattern = f"## {img.section_title}"

        if header_pattern in md_with_placeholders:
            md_with_placeholders = md_with_placeholders.replace(
                header_pattern, f"{header_pattern}\n\n{placeholder}\n"
            )
        else:
            md_with_placeholders += f"\n\n{placeholder}\n"

        spec_dict = img.model_dump()
        # Never trust the LLM-proposed filename as a path (path traversal guard).
        spec_dict["filename"] = _safe_image_filename(spec_dict.get("filename"), fallback_stem=f"image_{idx}")
        spec_dict["placeholder"] = placeholder
        image_specs_dict.append(spec_dict)

    return {
        "md_with_placeholders": md_with_placeholders,
        "image_specs": image_specs_dict,
        "workflow_step": "image-plan",
    }


# ============================================================
# Graph node: generate every planned image and splice it into the markdown
# ============================================================
def generate_and_place_images(state: State, config: Optional[RunnableConfig] = None) -> dict:
    """Generate images and splice them into the markdown.
    Uses workspace_dir from config for file isolation between concurrent runs.
    The API layer reads these files afterwards and stores them in the database.
    """
    config = config or {}
    mark_workflow_step(state.get("run_id"), "image-gen")
    workspace_dir = Path(
        (config.get("configurable") or {}).get("workspace_dir", ".")
    )

    plan = state["plan"]
    assert plan is not None
    plan = coerce_plan(plan)

    md = state.get("md_with_placeholders") or state["merged_md"]
    image_specs = state.get("image_specs", []) or []

    if not image_specs:
        return {"final": md, "workflow_step": "image-gen"}

    images_dir = workspace_dir / "images"
    images_dir.mkdir(parents=True, exist_ok=True)

    for spec in image_specs:
        placeholder = spec["placeholder"]
        filename = _safe_image_filename(spec.get("filename"), fallback_stem="image")
        out_path = (images_dir / filename).resolve()
        if images_dir.resolve() not in out_path.parents:
            filename = _safe_image_filename("image")
            out_path = (images_dir / filename).resolve()

        if not out_path.exists():
            try:
                width, height = _parse_image_size(spec.get("size"))
                img_bytes = _generate_image_with_retry(spec["prompt"], width=width, height=height)
                out_path.write_bytes(img_bytes)
            except Exception as e:
                logger.warning("Image '%s' could not be generated: %s", filename, e)
                fallback_block = "> **Image could not be generated**\n"
                md = md.replace(placeholder, fallback_block)
                continue

        img_md = f"![{spec['alt']}](images/{filename})\n*{spec['caption']}*"
        md = md.replace(placeholder, img_md)

    return {"final": md}