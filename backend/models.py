import uuid
from datetime import datetime, timezone

from sqlalchemy import (
    Column,
    Integer,
    String,
    Text,
    DateTime,
    LargeBinary,
    ForeignKey,
    Boolean,
)
from sqlalchemy.orm import relationship

from database import Base


def _utcnow():
    return datetime.now(timezone.utc)


class User(Base):
    __tablename__ = "users"

    id = Column(
        Integer,
        primary_key=True,
        index=True,
    )

    username = Column(
        String(150),
        unique=True,
        index=True,
        nullable=False,
    )

    email = Column(
        String(255),
        unique=True,
        index=True,
        nullable=False,
    )

    hashed_password = Column(
        String(255),
        nullable=False,
    )

    # Admin authorization flag
    is_admin = Column(
        Boolean,
        default=False,
        nullable=False,
    )

    created_at = Column(
        DateTime(timezone=True),
        default=_utcnow,
    )

    runs = relationship(
        "BlogRun",
        back_populates="user",
        cascade="all, delete-orphan",
    )

    # Security events generated by this user.
    audit_logs = relationship(
        "SecurityAuditLog",
        back_populates="user",
        cascade="all, delete-orphan",
    )


class BlogRun(Base):
    __tablename__ = "blog_runs"

    id = Column(
        String(36),
        primary_key=True,
        default=lambda: str(uuid.uuid4()),
    )

    user_id = Column(
        Integer,
        ForeignKey("users.id"),
        nullable=False,
        index=True,
    )

    thread_id = Column(
        String(36),
        default=lambda: str(uuid.uuid4()),
        index=True,
    )

    topic = Column(
        Text,
        nullable=False,
    )

    status = Column(
        String(20),
        default="pending",
    )

    # Last graph stage observed by the API. This is updated by workflow nodes
    # so the frontend can show real progress instead of guessing from artifacts.
    workflow_step = Column(
        String(50),
        nullable=True,
    )

    as_of = Column(
        String(10),
    )

    audience_pref = Column(
        String(100),
        nullable=True,
    )

    tone_pref = Column(
        String(100),
        nullable=True,
    )

    blog_kind_pref = Column(
        String(50),
        nullable=True,
    )

    plan_json = Column(
        Text,
        nullable=True,
    )

    evidence_json = Column(
        Text,
        nullable=True,
    )

    final_markdown = Column(
        Text,
        nullable=True,
    )

    image_specs_json = Column(
        Text,
        nullable=True,
    )

    interrupt_type = Column(
        String(50),
        nullable=True,
    )

    interrupt_data_json = Column(
        Text,
        nullable=True,
    )

    error_message = Column(
        Text,
        nullable=True,
    )

    guardrail_msg = Column(
        Text,
        nullable=True,
    )

    created_at = Column(
        DateTime(timezone=True),
        default=_utcnow,
    )

    updated_at = Column(
        DateTime(timezone=True),
        default=_utcnow,
        onupdate=_utcnow,
    )

    user = relationship(
        "User",
        back_populates="runs",
    )

    images = relationship(
        "BlogImage",
        back_populates="run",
        cascade="all, delete-orphan",
    )

    # Security events associated with this generation run.
    audit_logs = relationship(
        "SecurityAuditLog",
        back_populates="run",
        cascade="all, delete-orphan",
    )


class BlogImage(Base):
    __tablename__ = "blog_images"

    id = Column(
        Integer,
        primary_key=True,
        index=True,
    )

    run_id = Column(
        String(36),
        ForeignKey("blog_runs.id"),
        nullable=False,
        index=True,
    )

    filename = Column(
        String(255),
        nullable=False,
    )

    alt_text = Column(
        Text,
        nullable=True,
    )

    caption = Column(
        Text,
        nullable=True,
    )

    content_type = Column(
        String(50),
        default="image/png",
    )

    image_data = Column(
        LargeBinary,
        nullable=False,
    )

    created_at = Column(
        DateTime(timezone=True),
        default=_utcnow,
    )

    run = relationship(
        "BlogRun",
        back_populates="images",
    )


class SecurityAuditLog(Base):
    """
    Persistent security record for guardrail-triggered user input.

    input_type deliberately separates:
      - topic
      - subtopic
      - revision

    This prevents the Security page from having to guess whether a blocked
    value was the main topic or a generated/edited subtopic.
    """

    __tablename__ = "security_audit_logs"

    id = Column(
        Integer,
        primary_key=True,
        index=True,
    )

    user_id = Column(
        Integer,
        ForeignKey("users.id"),
        nullable=False,
        index=True,
    )

    run_id = Column(
        String(36),
        ForeignKey("blog_runs.id"),
        nullable=True,
        index=True,
    )

    # Snapshot the account information at the time of the security event.
    # This keeps the audit record understandable even if account information
    # changes later.
    username = Column(
        String(150),
        nullable=False,
    )

    email = Column(
        String(255),
        nullable=False,
    )

    # Explicitly identifies what kind of input triggered the guardrail.
    # Expected values: topic, subtopic, revision.
    input_type = Column(
        String(20),
        nullable=False,
        index=True,
    )

    # Main topic associated with the request.
    topic = Column(
        Text,
        nullable=False,
    )

    # Separate subtopic field. NULL when the event concerns the main topic.
    subtopic = Column(
        Text,
        nullable=True,
    )

    # Short machine-readable/human-readable category returned by the
    # guardrail, such as "malicious_instruction", "violence", etc.
    guardrail_category = Column(
        String(100),
        nullable=False,
    )

    # Original guardrail explanation shown to the user/admin.
    guardrail_message = Column(
        Text,
        nullable=False,
    )

    # Action taken by the system, for example "blocked".
    action = Column(
        String(30),
        nullable=False,
    )

    created_at = Column(
        DateTime(timezone=True),
        default=_utcnow,
        nullable=False,
        index=True,
    )

    user = relationship(
        "User",
        back_populates="audit_logs",
    )

    run = relationship(
        "BlogRun",
        back_populates="audit_logs",
    )